function rateEvent({ who, bank }, [date, change, level]) {
  const pct = (v) => `${Math.abs(v)}%`.replace(/^0\./, "0.");
  if (change === 0) {
    return { date, title: `${who}の金融緩和（預金金利の引き下げ）`, memory: `${bank}が、預け入れの金利をさらに下げた。` };
  }
  const up = change > 0;
  return {
    date,
    title: `${who}の${up ? "利上げ" : "利下げ"}（${level}%）`,
    memory: `${bank}が、金利を${pct(change)}${up ? "上げた" : "下げた"}。`,
  };
}

const RATES = BANKS.flatMap((b) => b.list.map((row) => rateEvent(b, row)));

// 同じ日に、手書きの出来事と同じ中央銀行の決定が重なるときは、手書きのほうだけを残す
function merged() {
  const manual = [...MAJOR, ...MORE].filter((e) => e.title);
  const out = [...manual];
  for (const e of RATES) {
    const dup = manual.some((m) => Math.abs(dayNo(m.date) - dayNo(e.date)) <= 1 && sameTopic(m.title, e.title));
    if (!dup) out.push(e);
  }
  return out.sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0));
}

function dayNo(d) {
  return Date.parse(d + "T00:00:00Z") / 86400000;
}

function sameTopic(a, b) {
  for (const key of ["アメリカ", "ユーロ", "ヨーロッパ", "オーストラリア", "イギリス", "協調"]) {
    if (a.includes(key) && (b.includes(key) || (key === "ヨーロッパ" && b.includes("ユーロ圏")))) return true;
  }
  return a.includes("協調");
}

export const EVENTS = merged();
